//! 神经声线转换的运行时层。
//!
//! # 它在产品里的位置
//!
//! 这个工具有两根柱子：**唱歌音准自动修正** 与 **声音克隆**。
//! 两根柱子的物理约束正好相反，谁也改不了对方：
//!
//! | | 实时（<30 ms，耳返里） | 离线（录完再处理） |
//! |---|---|---|
//! | 音准 | 实时修音 ✅ | 离线重新校准 ✅ |
//! | 声线 | DSP 塑形 ✅「像另一个人」 | **本 crate**「像某个指定的人」 |
//!
//! 修音必须 <30 ms，所以只能是纯 DSP、不能回看、不能用神经网络。
//! 克隆必须用神经网络，所以永远进不了 30 ms。**这不是缺陷，是产品结构。**
//!
//! # 三条红线在这里怎么落地
//!
//! **红线 1（实时链路 100% 在 Rust、采样点不过 IPC）** —— 与本 crate 无关：
//! 这里的一切都在引擎**停止**之后才跑。
//!
//! **红线 2（落盘的是原始干声）** —— 转换产物永远是**新文件**，绝不覆盖干声。
//! 干声是唯一不可再生的东西：模型可以换、参数可以改、声线可以重来，
//! 只有那段演唱重录不出来。
//!
//! **红线 3（推理绝不与实时音频线程抢 CPU）** —— 由 `AppState::start_offline`
//! 那道同款守卫拦住。推理比离线校准更吃 CPU，这条只会更严，不会放松。
//!
//! # 为什么内容编码器走 ONNX，而解码器将来要走 candle
//!
//! 内容编码器（ContentVec）是**冻结**的，永远不训练 —— 用现成的 ONNX 导出即可，
//! 不必在 Rust 里重写一遍 HuBERT。**导出件本身就是参考实现**，
//! 省掉了「权重加载对不上层名」这个最容易出、又最难查的错
//! （症状是"声音怪"而不是报错）。
//!
//! 解码器不一样：它要**按用户的素材训练**，而 `ort` 是纯推理、没有梯度。
//! 所以它将来用 `candle`，推理和训练共用同一份实现 ——
//! 同一个模型写两遍，两份只要有一处对不上，表现就是"能跑但不像"。
//!
//! # 体积
//!
//! 主程序仍然 6.5 MB 双击即用。想克隆的人多下约 215 MB（量化后）。
//! 不下载的人，四格里那三格一格不少。
//! 这是我认为唯一能同时守住「免安装单文件」和「支持克隆」的形态。

/// 特征对齐。**不依赖 onnx** —— 它是纯 DSP，默认构建就要编译并测试它。
///
/// 对齐错了模型学到的是垃圾，而且要等训练跑完才发现。
/// 这种东西不能藏在一个平时不编译的特性后面。
pub mod features;

/// 激励信号生成。同样不依赖 onnx —— 它只由 f0 决定，不含任何权重，
/// 是整个解码器里唯一能在没有模型时完整验证的部分。
pub mod source;

#[cfg(feature = "onnx")]
pub mod encoder;

#[cfg(feature = "onnx")]
pub mod session;

pub use features::{align, Aligned, Features};

/// 内容编码器期望的采样率。
///
/// ContentVec 建在 HuBERT 上，训练时就是 16 kHz —— 喂 48 kHz 进去
/// 不会报错，只会安静地给出垃圾特征。重采样是必需步骤，不是优化。
pub const ENCODER_RATE: u32 = 16_000;

/// 编码器输出的特征维度（`vec-768-layer-12`）。
pub const ENCODER_DIM: usize = 768;

/// 编码器的帧步进（样本 @16 kHz）。
///
/// HuBERT 的卷积前端固定 320 倍下采样 = 20 ms 一帧，也就是 50 fps。
/// f0 轨与响度包络都必须重采样到这个栅格上 ——
/// **对齐错了模型学到的是垃圾，而且要等训练跑完才发现。**
pub const ENCODER_HOP: usize = 320;
